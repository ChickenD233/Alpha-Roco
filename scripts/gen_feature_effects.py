def effect_for(desc: str) -> str:
    return EFFECT.get(desc, "已实现(见 data/feature_implementation.md)")


def main():
    spirits = json.load(open(ROOT / "data" / "spirits.json", encoding="utf-8"))["spirits"]
    spirits = sorted(spirits, key=lambda s: (len(s["no"]), s["no"]))
    start = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    end = int(sys.argv[2]) if len(sys.argv) > 2 else 100
    compact = "--compact" in sys.argv
    for s in spirits[start - 1:end]:
        f = s.get("feature") or {}
        name = s["name"]
        form = s.get("formType") or ""
        desc = f.get("desc", "无特性")
        eff = effect_for(desc)
        if compact:
            print(f"[{s['no']}] {name} ({form}) | {desc} → {eff}")
        else:
            print(f"[{s['no']}] {name} ({form})")
            print(f"    特性: {desc}")
            print(f"    效果: {eff}")
            print()


if __name__ == "__main__":
    main()
